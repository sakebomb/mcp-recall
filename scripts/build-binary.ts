/**
 * Builds the standalone mcp-recall binary with `bun build --compile` (#361):
 * one executable that runs the CLI, both hooks and the MCP server (`serve`),
 * with the bundled profiles embedded.
 *
 *   bun run build:binary                        # this machine's platform
 *   bun run build:binary --target bun-linux-arm64 [--target …]
 *   bun run build:binary --all                  # every release target
 *
 * Writes dist/bin/mcp-recall-<target>[.exe] and a .sha256 beside each. A
 * cross-compiled target downloads that platform's Bun runtime the first time.
 */
import { createHash } from "crypto";
import { mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "fs";
import { tmpdir } from "os";
import { join, relative } from "path";

export const RELEASE_TARGETS = [
  "bun-linux-x64",
  "bun-linux-arm64",
  "bun-darwin-x64",
  "bun-darwin-arm64",
  "bun-windows-x64",
];

const root = join(import.meta.dir, "..");

function profileFiles(dir: string): string[] {
  return readdirSync(dir).flatMap((n) => {
    const p = join(dir, n);
    return statSync(p).isDirectory() ? profileFiles(p) : [p];
  });
}

/** The binary's entry: each bundled profile embedded as a file, then src/binary.ts. */
export function entrySource(repo: string): string {
  const profilesDir = join(repo, "profiles");
  const files = profileFiles(profilesDir).sort();
  const imports = files.map((f, i) => `import p${i} from ${JSON.stringify(f)} with { type: "file" };`);
  const table = files.map((f, i) => `  [${JSON.stringify(relative(profilesDir, f))}, p${i}],`);
  return [
    "// Generated by scripts/build-binary.ts; not checked in.",
    ...imports,
    `import { runBinary } from ${JSON.stringify(join(repo, "src/binary.ts"))};`,
    "await runBinary([",
    ...table,
    "]);",
    "",
  ].join("\n");
}

function hostTarget(): string {
  const os = process.platform === "win32" ? "windows" : process.platform;
  return `bun-${os}-${process.arch}`;
}

function build(target: string, entry: string, outDir: string): string {
  const outfile = join(outDir, `mcp-recall-${target.replace(/^bun-/, "")}${target.includes("windows") ? ".exe" : ""}`);
  const p = Bun.spawnSync(["bun", "build", "--compile", "--minify", `--target=${target}`, entry, "--outfile", outfile], {
    cwd: root, stdout: "inherit", stderr: "inherit",
  });
  if (p.exitCode !== 0) throw new Error(`bun build --compile failed for ${target}`);
  const sha = createHash("sha256").update(readFileSync(outfile)).digest("hex");
  writeFileSync(`${outfile}.sha256`, `${sha}  ${outfile.split("/").pop()}\n`);
  return outfile;
}

if (import.meta.main) {
  const args = process.argv.slice(2);
  const targets = args.includes("--all")
    ? RELEASE_TARGETS
    : args.flatMap((a, i) => (a === "--target" && args[i + 1] ? [args[i + 1]!] : []));
  const outDir = join(root, "dist", "bin");
  mkdirSync(outDir, { recursive: true });
  const tmp = mkdtempSync(join(tmpdir(), "mcp-recall-entry-"));
  try {
    const entry = join(tmp, "entry.ts");
    writeFileSync(entry, entrySource(root));
    for (const t of targets.length ? targets : [hostTarget()]) {
      const out = build(t, entry, outDir);
      console.log(`${out}  ${(statSync(out).size / 1048576).toFixed(1)} MB`);
    }
  } finally {
    rmSync(tmp, { recursive: true, force: true });
  }
}
